CREATE TABLE CATEGORIES (
    CATEGORY_CODE INT PRIMARY KEY,
    CATEGORY_NAME VARCHAR(100),
    DESCRIPTION VARCHAR(255)
);

CREATE TABLE CUSTOMERS (
    CUSTOMER_CODE INT PRIMARY KEY,
    COMPANY VARCHAR(100),
    ADDRESS VARCHAR(255),
    CITY VARCHAR(100),
    POSTAL_CODE VARCHAR(20),
    COUNTRY VARCHAR(100),
    PHONE VARCHAR(50),
    FAX VARCHAR(50)
);




CREATE TABLE EMPLOYEES (
    EMPLOYEE_NUMBER INT PRIMARY KEY,
    REPORTS_TO INT,
    LAST_NAME VARCHAR(100),
    FIRST_NAME VARCHAR(100),
    POSITION VARCHAR(100),
    TITLE VARCHAR(10),
    BIRTH_DATE DATE,
    HIRE_DATE DATE,
    SALARY DECIMAL(10,2),
    COMMISSION DECIMAL(10,2),
    FOREIGN KEY (REPORTS_TO) REFERENCES EMPLOYEES(EMPLOYEE_NUMBER)
);


CREATE TABLE SUPPLIERS (
    SUPPLIER_NUMBER INT PRIMARY KEY,
    COMPANY VARCHAR(100),
    ADDRESS VARCHAR(255),
    CITY VARCHAR(100),
    POSTAL_CODE VARCHAR(20),
    COUNTRY VARCHAR(100),
    PHONE VARCHAR(50),
    FAX VARCHAR(50)
);


CREATE TABLE PRODUCTS (
    PRODUCT_REF INT PRIMARY KEY,
    PRODUCT_NAME VARCHAR(100),
    SUPPLIER_NUMBER INT,
    CATEGORY_CODE INT,
    QUANTITY VARCHAR(50),
    UNIT_PRICE DECIMAL(10,2),
    UNITS_IN_STOCK INT,
    UNITS_ON_ORDER INT,
    UNAVAILABLE INT,
    FOREIGN KEY (SUPPLIER_NUMBER) REFERENCES SUPPLIERS(SUPPLIER_NUMBER),
    FOREIGN KEY (CATEGORY_CODE) REFERENCES CATEGORIES(CATEGORY_CODE)
);


CREATE TABLE ORDERS (
    ORDER_NUMBER INT PRIMARY KEY,
    CUSTOMER_CODE INT,
    EMPLOYEE_NUMBER INT,
    ORDER_DATE DATE,
    SHIP_DATE DATE,
    SHIPPING_COST DECIMAL(10,2),
    FOREIGN KEY (CUSTOMER_CODE) REFERENCES CUSTOMERS(CUSTOMER_CODE),
    FOREIGN KEY (EMPLOYEE_NUMBER) REFERENCES EMPLOYEES(EMPLOYEE_NUMBER)
);


CREATE TABLE ORDER_DETAILS (
    ORDER_NUMBER INT,
    PRODUCT_REF INT,
    UNIT_PRICE DECIMAL(10,2),
    QUANTITY INT,
    DISCOUNT DECIMAL(5,2),
    PRIMARY KEY (ORDER_NUMBER, PRODUCT_REF),
    FOREIGN KEY (ORDER_NUMBER) REFERENCES ORDERS(ORDER_NUMBER),
    FOREIGN KEY (PRODUCT_REF) REFERENCES PRODUCTS(PRODUCT_REF)
);



