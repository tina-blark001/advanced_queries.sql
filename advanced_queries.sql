-- 1. Male employees with net salary >= 8000 ordered by seniority
SELECT 
    EMPLOYEE_NUMBER,
    FIRST_NAME,
    LAST_NAME,
    DATEDIFF(YEAR, BIRTH_DATE, GETDATE()) AS Age,
    DATEDIFF(YEAR, HIRE_DATE, GETDATE()) AS Seniority
FROM EMPLOYEES
WHERE TITLE = 'Mr'
  AND (SALARY + ISNULL(COMMISSION, 0)) >= 8000
ORDER BY Seniority DESC;









-- 2. Products meeting conditions C1–C5
SELECT 
    PRODUCT_REF,
    PRODUCT_NAME,
    SUPPLIER_NUMBER,
    UNITS_ON_ORDER,
    UNIT_PRICE
FROM PRODUCTS
WHERE QUANTITY LIKE '%bottle%'
  AND SUBSTRING(PRODUCT_NAME, 3, 1) IN ('t', 'T')
  AND SUPPLIER_NUMBER IN (1, 2, 3)
  AND UNIT_PRICE BETWEEN 70 AND 200
  AND UNITS_ON_ORDER IS NOT NULL;



